import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'apps/wechat-miniapp/miniprogram/data/catalog-seed.generated.js');
const source = process.env.SW_PUBLIC_CATALOG_URL || 'https://hbbtzn.com/api/v1/catalog/public/products?cursor=0&limit=200';

const response = await fetch(source, { headers: { accept: 'application/json' }, signal: AbortSignal.timeout(20_000) });
if (!response.ok) throw new Error(`Catalog seed request failed (${response.status})`);
const body = await response.json();
if (!body || !Array.isArray(body.items) || body.items.length === 0 || body.items.length > 200) {
  throw new Error('Catalog seed response must contain between 1 and 200 items');
}

const items = body.items.map((item) => ({
  id: item.id,
  skuId: item.skuId,
  name: item.name,
  subtitle: item.subtitle,
  categoryCode: item.categoryCode,
  taxonomy: item.taxonomy,
  coverUrl: item.coverUrl,
  priceCents: item.priceCents,
  marketPriceCents: item.marketPriceCents,
  availableStock: item.availableStock,
  supplierName: item.supplierName,
  isTest: item.isTest,
  purchasable: item.purchasable,
}));

const seed = {
  version: 1,
  source,
  generatedAt: new Date().toISOString(),
  items,
};
const output = `/* GENERATED by scripts/build-miniapp-catalog-seed.mjs — do not edit. */\nmodule.exports = ${JSON.stringify(seed)};\n`;
await mkdir(path.dirname(target), { recursive: true });
await writeFile(target, output, 'utf8');
console.log(`Mini-program catalog seed generated: ${items.length} products`);

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'apps/wechat-miniapp/miniprogram/data/catalog-seed.generated.js');
const criticalTarget = path.join(root, 'apps/wechat-miniapp/miniprogram/data/catalog-seed-critical.generated.js');
const source = process.env.SW_PUBLIC_CATALOG_URL || 'https://hbbtzn.com/api/v1/catalog/public/products?cursor=0&limit=200';
const fromExisting = process.argv.includes('--from-existing');

let body;
let generatedAt = new Date().toISOString();
let seedSource = source;
if (fromExisting) {
  const existingSource = await readFile(target, 'utf8');
  const existingModule = { exports: {} };
  new Function('module', 'exports', existingSource)(existingModule, existingModule.exports);
  const existing = existingModule.exports;
  body = { items: existing.items };
  generatedAt = existing.generatedAt || generatedAt;
  seedSource = existing.source || seedSource;
} else {
  const response = await fetch(source, { headers: { accept: 'application/json' }, signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`Catalog seed request failed (${response.status})`);
  body = await response.json();
}
if (!body || !Array.isArray(body.items) || body.items.length === 0 || body.items.length > 200) {
  throw new Error('Catalog seed response must contain between 1 and 200 items');
}

const items = body.items.map((item) => ({
  id: item.id,
  skuId: item.skuId,
  name: item.name,
  subtitle: item.subtitle,
  categoryCode: item.categoryCode,
  taxonomy: item.taxonomy,
  coverUrl: item.coverUrl,
  priceCents: item.priceCents,
  marketPriceCents: item.marketPriceCents,
  availableStock: item.availableStock,
  supplierName: item.supplierName,
  isTest: item.isTest,
  purchasable: item.purchasable,
}));

const seed = {
  version: 1,
  source: seedSource,
  generatedAt,
  items,
};
const criticalItems = selectCriticalItems(items, 24);
const criticalSeed = {
  version: 1,
  source: seedSource,
  generatedAt: seed.generatedAt,
  complete: false,
  items: criticalItems,
};
const output = `/* GENERATED by scripts/build-miniapp-catalog-seed.mjs — do not edit. */\nmodule.exports = ${JSON.stringify(seed)};\n`;
const criticalOutput = `/* GENERATED by scripts/build-miniapp-catalog-seed.mjs — do not edit. */\nmodule.exports = ${JSON.stringify(criticalSeed)};\n`;
await mkdir(path.dirname(target), { recursive: true });
await writeFile(target, output, 'utf8');
await writeFile(criticalTarget, criticalOutput, 'utf8');
console.log(`Mini-program catalog seeds generated: ${criticalItems.length} critical / ${items.length} complete products`);

function selectCriticalItems(products, limit) {
  const groups = new Map();
  for (const product of products) {
    const key = product?.taxonomy?.l1 || product?.categoryCode || 'other';
    const group = groups.get(key) || [];
    group.push(product);
    groups.set(key, group);
  }
  const selected = [];
  const queues = [...groups.values()];
  while (selected.length < limit && queues.some((queue) => queue.length)) {
    for (const queue of queues) {
      if (queue.length && selected.length < limit) selected.push(queue.shift());
    }
  }
  return selected;
}
